const languageButtons = document.querySelectorAll('[data-language]');
const form = document.querySelector('#booking-form');
const message = document.querySelector('#form-message');
const submitButton = document.querySelector('#submit-booking');
const bookingSection = document.querySelector('#booking');
const bookingIntro = document.querySelector('#booking-intro');
const serviceDetail = document.querySelector('#service-detail');
const serviceDetailTitle = document.querySelector('#service-detail-title');
const serviceDetailDescription = document.querySelector('#service-detail-description');
const bookingServiceSelect = form.querySelector('[name="service"]');
const serviceDetails = JSON.parse(
  document.querySelector('#service-details-data').textContent,
);
const servicesBySlug = new Map(serviceDetails.map((service) => [service.slug, service]));
let currentLanguage = 'hi';
let messageKey = '';
let activeService = null;

try {
  const savedLanguage = localStorage.getItem('pandit-ji-language');
  if (Object.prototype.hasOwnProperty.call(translations, savedLanguage)) {
    currentLanguage = savedLanguage;
  }
} catch {
  // Keep Hindi as the default when browser storage is unavailable.
}

function setStatus(key) {
  messageKey = key;
  message.textContent = key ? translations[currentLanguage][key] : '';
}

function updateServiceCards() {
  document.querySelectorAll('[data-service-slug]').forEach((button) => {
    const service = servicesBySlug.get(button.dataset.serviceSlug);
    if (!service) return;
    button.querySelector('[data-service-name]').textContent =
      currentLanguage === 'hi' ? service.name_hi : service.name_en;
    button.setAttribute(
      'aria-label',
      currentLanguage === 'hi' ? service.name_hi : service.name_en,
    );
  });

  if (activeService) {
    serviceDetailTitle.textContent =
      currentLanguage === 'hi' ? activeService.name_hi : activeService.name_en;
    serviceDetailDescription.textContent =
      currentLanguage === 'hi' ? activeService.description_hi : activeService.description_en;
  }
}

function showServiceDetail(slug) {
  const service = servicesBySlug.get(slug);
  if (!service) {
    console.error(`No service details configured for "${slug}".`);
    return;
  }

  activeService = service;
  updateServiceCards();
  bookingIntro.hidden = true;
  form.hidden = true;
  serviceDetail.hidden = false;
  bookingSection.classList.add('is-detail-mode');
  bookingSection.scrollIntoView({behavior: 'smooth', block: 'start'});
  serviceDetailTitle.focus({preventScroll: true});
}

function showBookingForm(bookingService = null, focusService = false) {
  bookingSection.classList.remove('is-detail-mode');
  serviceDetail.hidden = true;
  bookingIntro.hidden = false;
  form.hidden = false;
  activeService = null;
  if (bookingService) {
    const option = bookingServiceSelect.querySelector(
      `[data-booking-service="${bookingService}"]`,
    );
    if (!option) {
      console.error(`No booking option configured for "${bookingService}".`);
    } else {
      bookingServiceSelect.value = option.value;
    }
  }
  bookingSection.scrollIntoView({behavior: 'smooth', block: 'start'});
  if (focusService) bookingServiceSelect.focus({preventScroll: true});
}

function setLanguage(language, persist = true) {
  if (!Object.prototype.hasOwnProperty.call(translations, language)) return;
  currentLanguage = language;
  const text = translations[language];
  document.documentElement.lang = language;
  document.title = text.pageTitle;
  document.querySelector('meta[name="description"]').content = text.pageDescription;

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    element.textContent = text[element.dataset.i18n];
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((element) => {
    element.setAttribute('aria-label', text[element.dataset.i18nAria]);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    element.placeholder = text[element.dataset.i18nPlaceholder];
  });
  document.querySelectorAll('[data-i18n-value]').forEach((element) => {
    element.value = text[element.dataset.i18nValue];
  });
  updateServiceCards();

  languageButtons.forEach((button) => {
    const active = button.dataset.language === language;
    button.classList.toggle('is-active', active);
    button.setAttribute('aria-pressed', String(active));
  });

  const emailSubject = language === 'hi' ? 'पंडित जी पूछताछ' : 'Pandit Ji Enquiry';
  document.querySelector('.nav-links .contact').href =
    `mailto:prateek.chaurasia2728@gmail.com?subject=${encodeURIComponent(emailSubject)}`;
  document.querySelector('#whatsapp-link').href =
    `https://wa.me/918077847343?text=${encodeURIComponent(text.whatsappMessage)}`;
  setStatus(messageKey);

  if (persist) {
    try {
      localStorage.setItem('pandit-ji-language', language);
    } catch {
      // The language switch still works for this visit when storage is unavailable.
    }
  }
}

languageButtons.forEach((button) => {
  button.addEventListener('click', () => setLanguage(button.dataset.language));
});

document.querySelectorAll('[data-service-slug]').forEach((button) => {
  button.addEventListener('click', () => showServiceDetail(button.dataset.serviceSlug));
});
document.querySelectorAll('[data-scroll-to]').forEach((link) => {
  link.addEventListener('click', (event) => {
    event.preventDefault();
    const target = document.getElementById(link.dataset.scrollTo);
    if (target) target.scrollIntoView({behavior: 'smooth', block: 'start'});
  });
});
document.querySelectorAll('[data-open-booking]').forEach((link) => {
  link.addEventListener('click', (event) => {
    event.preventDefault();
    showBookingForm();
  });
});
document.querySelector('#service-back').addEventListener('click', () => showBookingForm());
document.querySelector('#service-booking').addEventListener('click', () => {
  showBookingForm(activeService?.booking_service, true);
});
setLanguage(currentLanguage, false);

form.addEventListener('submit', async (event) => {
  event.preventDefault();
  if (!form.checkValidity()) {
    setStatus('invalid');
    form.querySelector(':invalid')?.focus();
    return;
  }

  const data = Object.fromEntries(new FormData(form));
  const csrfToken = form.querySelector('[name="csrfmiddlewaretoken"]').value;
  submitButton.disabled = true;
  setStatus('sending');

  try {
    const response = await fetch('/api/bookings', {
      method: 'POST',
      headers: {'Content-Type': 'application/json', 'X-CSRFToken': csrfToken},
      body: JSON.stringify(data),
    });
    if (!response.ok) {
      const result = await response.json().catch(() => null);
      const errorKey = response.status === 400
        ? 'invalid'
        : response.status === 503
          ? 'emailConfigSaved'
          : response.status === 502
            ? 'emailFailedSaved'
            : 'unavailable';
      if (result?.booking_id) {
        setStatus(errorKey);
        message.textContent = translations[currentLanguage][errorKey]
          .replace('{id}', result.booking_id);
      } else {
        setStatus(errorKey);
      }
      return;
    }
    form.reset();
    setStatus('success');
  } catch {
    setStatus('unavailable');
  } finally {
    submitButton.disabled = false;
  }
});

if ('serviceWorker' in navigator) navigator.serviceWorker.register('/sw.js');
